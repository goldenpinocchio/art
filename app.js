const stage = document.querySelector('#stage');
const cards = [];
let W, H, CW, CH;
const reduced = window.matchMedia('(prefers-reduced-motion: reduce)');
const LOAD_MARGIN = 2.2;
const CARD_GAP = 1;
// Keep several passes of the collection active in the stream. Repeated artwork
// is preferable to an empty band: the cards should feel like a continuous fall
// from the moment the page opens.
const POOL_SIZE = ARTWORK.length * 4;
const STREAM_SPEED = .9;
const STREAM_ACCEL = .004;
const AIR_DRAG = .985;
const COLLISION_RESTITUTION = .08;
const COLLISION_CORRECTION = .25;
const MAX_DRAG_SPEED = 8;
const THROW_TIME = 95;
const lightbox = document.querySelector('#lightbox');
const lightboxCard = lightbox.querySelector('.lightbox-card');
const lightboxImage = lightbox.querySelector('.lightbox-front img');
const lightboxName = lightbox.querySelector('.lightbox-name');
const lightboxLink = lightbox.querySelector('.lightbox-link');
let nextArtwork = 0;

function size() {
  const compact = matchMedia('(max-width: 700px)').matches;
  CW = compact ? 100 : 120;
  CH = compact ? 140 : 170;
  W = stage.clientWidth;
  H = stage.clientHeight;
}

function addCard(item, i) {
  const el = document.createElement('button');
  el.className = 'card';
  el.type = 'button';
  el.setAttribute('aria-label', `${item.name} — click to view details`);
  el.innerHTML = `<span class="card-inner"><span class="card-face card-front"><span class="image-placeholder" aria-hidden="true"></span><img alt="${item.name}" decoding="async"></span><span class="card-face card-back"><span class="card-name">${item.name}</span><span class="card-meta"><strong>Supply</strong>0</span><a class="card-link" href="${item.url}" target="_blank" rel="noopener">View on TokenScan ↗</a></span></span>`;
  const image = el.querySelector('img');
  image.addEventListener('load', () => el.classList.add('image-loaded'));
  image.addEventListener('error', () => { el.classList.add('image-error'); image.alt = `${item.name} image unavailable`; });
  const artifact = {
    el, item, x: 0, y: 0, vx: 0, vy: STREAM_SPEED, phase: i * 1.73,
    dragging: false, pointerId: null, grabX: 0, grabY: 0,
    lastX: 0, lastY: 0, lastTime: 0, wasDragged: false,
    loaded: false, throwTimer: 0, active: true, lane: 0
  };
  el.addEventListener('click', e => {
    if (!e.target.closest('a') && !artifact.wasDragged) openLightbox(artifact);
    artifact.wasDragged = false;
  });
  el.addEventListener('pointerdown', e => {
    if (e.button !== 0 || e.target.closest('a')) return;
    const rect = stage.getBoundingClientRect();
    artifact.dragging = true;
    artifact.pointerId = e.pointerId;
    artifact.wasDragged = false;
    artifact.throwTimer = 0;
    artifact.grabX = e.clientX - rect.left - artifact.x;
    artifact.grabY = e.clientY - rect.top - artifact.y;
    artifact.lastX = artifact.x;
    artifact.lastY = artifact.y;
    artifact.lastTime = performance.now();
    try { el.setPointerCapture(e.pointerId); } catch (_) {}
    el.classList.add('is-dragging');
    e.preventDefault();
  });
  el.addEventListener('pointermove', e => {
    if (!artifact.dragging || e.pointerId !== artifact.pointerId) return;
    const rect = stage.getBoundingClientRect();
    const nx = e.clientX - rect.left - artifact.grabX;
    const ny = e.clientY - rect.top - artifact.grabY;
    if (Math.hypot(nx - artifact.x, ny - artifact.y) > 5) artifact.wasDragged = true;
    const now = performance.now();
    const elapsed = Math.max(8, now - artifact.lastTime);
    artifact.vx = Math.max(-MAX_DRAG_SPEED, Math.min(MAX_DRAG_SPEED, (nx - artifact.lastX) / elapsed * 16.67));
    artifact.vy = Math.max(-MAX_DRAG_SPEED, Math.min(MAX_DRAG_SPEED, (ny - artifact.lastY) / elapsed * 16.67));
    artifact.lastX = nx;
    artifact.lastY = ny;
    artifact.lastTime = now;
    artifact.x = Math.max(0, Math.min(W - CW, nx));
    artifact.y = ny;
    render();
  });
  const release = e => {
    if (!artifact.dragging || e.pointerId !== artifact.pointerId) return;
    artifact.dragging = false;
    artifact.pointerId = null;
    artifact.throwTimer = THROW_TIME;
    // Keep most of the release velocity so throwing is obvious but controlled.
    artifact.vx *= .9;
    artifact.vy *= .9;
    el.classList.remove('is-dragging');
  };
  el.addEventListener('pointerup', release);
  el.addEventListener('pointercancel', release);
  stage.appendChild(el);
  return artifact;
}

function clamp(a) {
  if (a.x < 0) { a.x = 0; a.vx = Math.abs(a.vx) * .65; }
  if (a.x > W - CW) { a.x = W - CW; a.vx = -Math.abs(a.vx) * .65; }
}

function collide(a, b) {
  const dx = (b.x + CW / 2) - (a.x + CW / 2);
  const dy = (b.y + CH / 2) - (a.y + CH / 2);
  const overlapX = CW + CARD_GAP - Math.abs(dx);
  const overlapY = CH + CARD_GAP - Math.abs(dy);
  if (overlapX <= 0 || overlapY <= 0) return;
  const horizontal = overlapX < overlapY;
  const nx = horizontal ? (dx < 0 ? -1 : 1) : 0;
  const ny = horizontal ? 0 : (dy < 0 ? -1 : 1);
  const penetration = horizontal ? overlapX : overlapY;
  const push = penetration * COLLISION_CORRECTION;
  if (!a.dragging) { a.x -= nx * push; a.y -= ny * push; }
  if (!b.dragging) { b.x += nx * push; b.y += ny * push; }
  const relative = (b.vx - a.vx) * nx + (b.vy - a.vy) * ny;
  if (relative < 0) {
    const impulse = -relative * (1 + COLLISION_RESTITUTION) * .06;
    if (!a.dragging) { a.vx -= impulse * nx; a.vy -= impulse * ny; }
    if (!b.dragging) { b.vx += impulse * nx; b.vy += impulse * ny; }
  }
}

function render() {
  cards.forEach(a => { a.el.style.transform = `translate3d(${a.x}px,${a.y}px,0)`; });
}

function lazyLoad(a) {
  const nearViewport = a.y > -CH * LOAD_MARGIN && a.y < H + CH * LOAD_MARGIN;
  if (nearViewport && !a.loaded) {
    const image = a.el.querySelector('img');
    image.src = `All Images/${encodeURIComponent(a.item.file)}`;
    a.loaded = true;
  }
  a.el.classList.toggle('near-viewport', nearViewport);
}

function updateCard(a, item) {
  a.item = item;
  a.loaded = false;
  a.el.classList.remove('image-loaded', 'image-error', 'is-flipped');
  a.el.setAttribute('aria-label', `${item.name} — click to view details`);
  a.el.querySelector('img').alt = item.name;
  a.el.querySelector('img').removeAttribute('src');
  a.el.querySelector('.card-name').textContent = item.name;
  a.el.querySelector('.card-link').href = item.url;
  lazyLoad(a);
}

function openLightbox(a) {
  lightboxImage.src = `All Images/${encodeURIComponent(a.item.file)}`;
  lightboxImage.alt = a.item.name;
  lightboxName.textContent = a.item.name;
  lightboxLink.href = a.item.url;
  lightboxCard.classList.remove('is-flipped');
  lightbox.hidden = false;
  lightbox.setAttribute('aria-hidden', 'false');
  requestAnimationFrame(() => lightbox.classList.add('is-open'));
}

function closeLightbox() {
  lightbox.classList.remove('is-open');
  lightbox.setAttribute('aria-hidden', 'true');
  setTimeout(() => { lightbox.hidden = true; }, 220);
}

lightboxCard.addEventListener('click', e => { if (!e.target.closest('a')) lightboxCard.classList.toggle('is-flipped'); });
lightboxCard.addEventListener('keydown', e => {
  if ((e.key === 'Enter' || e.key === ' ') && !e.target.closest('a')) {
    e.preventDefault();
    lightboxCard.classList.toggle('is-flipped');
  }
});
lightbox.querySelector('.lightbox-close').addEventListener('click', closeLightbox);
lightbox.addEventListener('click', e => { if (e.target === lightbox) closeLightbox(); });
addEventListener('keydown', e => { if (e.key === 'Escape' && !lightbox.hidden) closeLightbox(); });

function seed() {
  size();
  // Keep the opening stream dense: cards begin just above the viewport and
  // each lane advances by roughly one card height, so the whole stage is
  // occupied while the first cards are already falling.
  const columns = Math.max(4, Math.min(10, Math.floor(W / (CW + 18))));
  const laneWidth = Math.max(1, W - CW);
  const rowGap = CH * .84;
  cards.forEach((a, i) => {
    const column = i % columns;
    const row = Math.floor(i / columns);
    const lane = columns === 1 ? 0 : column / (columns - 1);
    const jitter = ((i * 29) % 11) - 5;
    const verticalJitter = ((i * 47) % 11) - 5;
    a.x = Math.max(0, Math.min(laneWidth, lane * laneWidth + jitter));
    a.y = -CH * .35 + row * rowGap + verticalJitter;
    a.lane = column;
    a.vx = ((i % 5) - 2) * .025;
    a.vy = STREAM_SPEED;
    lazyLoad(a);
  });
  render();
}

function recycle(a) {
  updateCard(a, ARTWORK[nextArtwork % ARTWORK.length]);
  nextArtwork += 1;
  // Re-enter immediately behind the leader in this card's own lane. A global
  // leader allowed one column to get ahead and left an empty band.
  const columns = Math.max(4, Math.min(10, Math.floor(W / (CW + 18))));
  const laneWidth = Math.max(1, W - CW);
  a.lane = (a.lane + 1) % columns;
  const lane = columns === 1 ? 0 : a.lane / (columns - 1);
  const jitter = ((nextArtwork * 29) % 17) - 8;
  a.x = Math.max(0, Math.min(laneWidth, lane * laneWidth + jitter));
  const laneCards = cards.filter(card => card !== a && card.lane === a.lane);
  const highest = laneCards.length ? Math.min(...laneCards.map(card => card.y)) : -CH;
  a.y = highest - CH;
  a.vx = ((nextArtwork % 5) - 2) * .025;
  a.vy = STREAM_SPEED;
  a.throwTimer = 0;
}

let last = performance.now();
function tick(now) {
  const dt = Math.min(32, now - last) / 16.67;
  last = now;
  if (!reduced.matches && document.visibilityState === 'visible') {
    cards.forEach(a => {
      if (!a.dragging) {
        if (a.throwTimer > 0) {
          a.throwTimer -= dt;
          a.vy += STREAM_ACCEL * dt;
          a.vx *= Math.pow(AIR_DRAG, dt);
          a.vy *= Math.pow(AIR_DRAG, dt);
        } else {
          a.vy += (STREAM_SPEED - a.vy) * .035 * dt;
          a.vx *= Math.pow(.995, dt);
          a.vx += Math.sin(now * .00031 + a.phase) * .0012 * dt;
        }
        a.x += a.vx * dt;
        a.y += a.vy * dt;
      }
      clamp(a);
      lazyLoad(a);
    });
    for (let i = 0; i < cards.length; i++) for (let j = i + 1; j < cards.length; j++) {
      const a = cards[i], b = cards[j];
      if (Math.abs(a.y - b.y) < CH * 1.15 && Math.abs(a.x - b.x) < CW * 1.15) collide(a, b);
    }
    cards.forEach(a => {
      clamp(a);
      if (!a.dragging && a.y > H + CH * 1.1) recycle(a);
    });
    render();
  }
  requestAnimationFrame(tick);
}

for (let i = 0; i < POOL_SIZE; i++) {
  const item = ARTWORK[i % ARTWORK.length];
  const a = addCard(item, i);
  cards.push(a);
}
nextArtwork = POOL_SIZE;
addEventListener('resize', () => { size(); cards.forEach(clamp); render(); });
seed();
requestAnimationFrame(tick);


